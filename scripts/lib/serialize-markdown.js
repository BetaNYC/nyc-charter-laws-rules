// The Markdown index (data/index/markdown/<corpus>.md), written from renderSection's blocks.
//
// The Markdown is the bulk download, and its bytes must not change with the structure work
// (issue #61): the body stays one paragraph, the blocks joined with one space, which is the
// section's `text` exactly. test/markdown-parity.test.js rebuilds the committed Markdown from
// the committed JSON with this module and compares every byte.

import { renderSection, bodyBlocks } from "./render-section.js";

export const CORPUS_LABELS = {
  charter: "NYC Charter",
  admin_code: "NYC Administrative Code",
  rules: "Rules of the City of New York",
};

/** One section: heading, citation, then its body as one paragraph. */
export function sectionMarkdown(blocks) {
  const heading = blocks.find((b) => b.type === "heading")?.text ?? "";
  const citation = blocks.find((b) => b.type === "citation")?.text ?? "";
  const body = bodyBlocks(blocks).map((b) => b.text).join(" ");
  return [
    `## ${heading}`,
    ``,
    `**Citation:** ${citation}`,
    ``,
    body || "_No text extracted._",
    ``,
    `---`,
    ``,
  ].join("\n");
}

/**
 * The whole Markdown file for one corpus. `structure` is the structure file's object for the
 * corpus (or null): its sections line up one to one with `sections`.
 */
export function corpusMarkdown({ corpus, version, sections, structure = null }) {
  if (structure && structure.sections.length !== sections.length) {
    throw new Error(`structure for ${corpus} has ${structure.sections.length} sections, the index ${sections.length}`);
  }
  return [
    `# ${CORPUS_LABELS[corpus]}`,
    ``,
    `> ${version}`,
    ``,
    `_${sections.length} sections indexed. Generated by [nyc-charter-laws-rules](https://github.com/BetaNYC/nyc-charter-laws-rules)._`,
    ``,
    `---`,
    ``,
    ...sections.map((s, i) => sectionMarkdown(renderSection(s, structure ? structure.sections[i] : null))),
  ].join("\n");
}
